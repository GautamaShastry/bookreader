def fixture_ids(fixture_id: str) -> tuple[str, str]:
    """Stable (book_id, book_version_id) for a fixture; independent of platform file bytes."""
    book = uuid.uuid5(FIXTURE_NAMESPACE, f"book:{fixture_id}")
    version = uuid.uuid5(FIXTURE_NAMESPACE, f"version:{fixture_id}:1")
    return str(book), str(version)


def norm(text: str) -> str:
    """Canonical normalisation used for gold quotes: NFKC + collapsed whitespace."""
    return " ".join(unicodedata.normalize("NFKC", text).split())


