_FONT = pymupdf.Font("helv")


def _new_doc() -> pymupdf.Document:
    return pymupdf.open()


def _page(doc: pymupdf.Document) -> pymupdf.Page:
    page = doc.new_page(width=595, height=842)
    page.insert_font(fontname="F0", fontbuffer=_FONT.buffer)
    return page


def _write_lines(
    page: pymupdf.Page, lines: list[str], *, heading: bool, order: list[int] | None = None
) -> None:
    """Write lines top-to-bottom visually; ``order`` controls content-stream insertion order."""
    positions = []
    y = 100.0
    for i, line in enumerate(lines):
        size = 20.0 if heading and i == 0 else 11.0
        positions.append((y, size, line))
        y += 40.0 if heading and i == 0 else 24.0
    for i in order if order is not None else range(len(lines)):
        y, size, line = positions[i]
        page.insert_text((72, y), line, fontname="F0", fontsize=size)


def _raster(page: pymupdf.Page) -> None:
    """Draw a shape and embed a tiny raster image: visual content with no extractable text."""
    page.draw_rect(pymupdf.Rect(100, 100, 495, 400), color=(0, 0, 0), fill=(0.8, 0.8, 0.9))
    pix = pymupdf.Pixmap(pymupdf.csRGB, pymupdf.IRect(0, 0, 8, 8), False)
    pix.set_rect(pix.irect, (40, 90, 160))
    page.insert_image(pymupdf.Rect(150, 450, 450, 750), pixmap=pix)


def _pdf_bytes(doc: pymupdf.Document, title: str, **save: Any) -> bytes:
    doc.set_metadata({**PDF_META, "title": title})
    return bytes(doc.tobytes(garbage=4, deflate=True, no_new_id=True, **save))


def _unit(gold: Gold, index: int, status: str, lines: list[str] | None = None) -> None:
    unit: dict[str, Any] = {"source_id": gold.unit_id(index), "status": status}
    if gold.fmt == "pdf":
        unit["page_index"] = index
    if lines:
        unit["first_line"] = norm(lines[0])
        unit["last_line"] = norm(lines[-1])
    gold.source_units.append(unit)


def _quote(gold: Gold, qid: str, text: str, indices: list[int], **extra: Any) -> None:
    gold.quotes.append(
        {
            "quote_id": f"{gold.fixture_id}:{qid}",
            "text": norm(text),
            "expected_source_ids": [gold.unit_id(i) for i in indices],
            "ambiguous": len(indices) > 1,
            **extra,
        }
    )


