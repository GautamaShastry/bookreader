def _still_encrypted(path: Path) -> bool:
    try:
        return bool(pymupdf.open(path).needs_pass)
    except Exception:
        return False


def build(reuse: Path | None = BOOKS) -> tuple[dict[str, bytes], dict[str, Any]]:
    """Generate all fixtures. Non-deterministic files already in ``reuse`` are kept as-is."""
    files: dict[str, bytes] = {}
    fixtures = []
    for generate in GENERATORS:
        data, gold = generate()
        filename = f"{gold.fixture_id}.{gold.fmt}"
        existing = reuse / filename if reuse else None
        if not gold.deterministic and existing and _still_encrypted(existing):
            data = existing.read_bytes()
        files[filename] = data
        book_id, book_version_id = fixture_ids(gold.fixture_id)
        fixtures.append(
            {
                "fixture_id": gold.fixture_id,
                "book_id": book_id,
                "book_version_id": book_version_id,
                "path": f"books/{filename}",
                "format": gold.fmt,
                "media_type": "application/pdf" if gold.fmt == "pdf" else "application/epub+zip",
                "sha256": hashlib.sha256(data).hexdigest(),
                "size_bytes": len(data),
                "deterministic": gold.deterministic,
                "title": gold.title,
                "description": gold.description,
                "license": LICENSE,
                "expected_outcome": gold.outcome,
                "source_units": gold.source_units,
                "chapters": gold.chapters,
                "quotes": gold.quotes,
                "label_source": "generator",
                "reviewer_status": "pending_human_review",
            }
        )
    manifest = {
        "manifest_version": "1.0.0",
        "spec_version": "1.4.0",
        "generator": {"script": "scripts/generate_fixtures.py", "version": GENERATOR_VERSION},
        "normalization": "NFKC, whitespace collapsed to single spaces, trimmed",
        "fixtures": fixtures,
    }
    return files, manifest


def _dump(manifest: dict[str, Any]) -> str:
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def write(target: Path, reuse: Path | None = BOOKS) -> None:
    files, manifest = build(reuse)
    books = target / "books"
    books.mkdir(parents=True, exist_ok=True)
    for stale in books.iterdir():
        if stale.name not in files:
            stale.unlink()
    for name, data in files.items():
        (books / name).write_bytes(data)
    (target / "manifest.json").write_text(_dump(manifest), encoding="utf-8", newline="\n")


def _without_hash(entry: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in entry.items() if k not in {"sha256", "size_bytes"}}


def _zip_fingerprint(path: Path) -> list[tuple[str, int, int, int]]:
    with zipfile.ZipFile(path) as zf:
        return [(i.filename, i.CRC, i.file_size, i.compress_type) for i in zf.infolist()]


def check() -> list[str]:
    """Compare committed fixtures with a fresh generation."""
    problems = []
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp)
        write(fresh, reuse=None)
        committed = json.loads(MANIFEST.read_text(encoding="utf-8"))
        regenerated = json.loads((fresh / "manifest.json").read_text(encoding="utf-8"))
        by_id = {f["fixture_id"]: f for f in committed["fixtures"]}
        for entry in regenerated["fixtures"]:
            old = by_id.pop(entry["fixture_id"], None)
            if old is None:
                problems.append(f"missing from committed manifest: {entry['fixture_id']}")
                continue
            if entry["deterministic"] and entry["format"] == "epub":
                # zlib output can differ by platform: compare uncompressed entries instead.
                if _without_hash(old) != _without_hash(entry):
                    problems.append(f"manifest labels differ: {entry['fixture_id']}")
                if _zip_fingerprint(FIXTURES / old["path"]) != _zip_fingerprint(
                    fresh / entry["path"]
                ):
                    problems.append(f"EPUB entries differ: {old['path']}")
            elif entry["deterministic"]:
                if old != entry:
                    problems.append(f"manifest entry differs: {entry['fixture_id']}")
                committed_bytes = (FIXTURES / old["path"]).read_bytes()
                if committed_bytes != (fresh / entry["path"]).read_bytes():
                    problems.append(f"file bytes differ: {old['path']}")
            else:
                if not _still_encrypted(FIXTURES / old["path"]):
                    problems.append(f"no longer an encrypted PDF: {old['path']}")
                if _without_hash(old) != _without_hash(entry):
                    problems.append(f"manifest labels differ: {entry['fixture_id']}")
        problems += [f"stale committed fixture: {fid}" for fid in by_id]
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for p in problems:
            print(f"FAIL: {p}")
        if problems:
            return 1
        print("PASS: committed fixtures match a fresh generation")
        return 0
    write(FIXTURES)
    print(f"wrote {len(GENERATORS)} fixtures to {BOOKS.relative_to(ROOT)} and manifest.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
