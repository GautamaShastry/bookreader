CONTAINER = """<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
"""


def _xhtml(title: str, body: str) -> str:
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">
<head><title>{title}</title></head>
<body>
{body}
</body>
</html>
"""


def _zip(
    entries: list[tuple[str, bytes | str]], *, mimetype: bytes = b"application/epub+zip"
) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as zf:
        info = zipfile.ZipInfo("mimetype", ZIP_DATE)
        info.compress_type = zipfile.ZIP_STORED
        zf.writestr(info, mimetype)
        for name, data in entries:
            info = zipfile.ZipInfo(name, ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, data.encode("utf-8") if isinstance(data, str) else data)
    return buffer.getvalue()


def _opf(
    title: str,
    items: list[tuple[str, str, str, str]],
    spine: list[str],
    *,
    version: str = "3.0",
    toc_attr: str = "",
    doctype: str = "",
) -> str:
    manifest = "\n    ".join(
        f'<item id="{i}" href="{h}" media-type="{m}"{p}/>' for i, h, m, p in items
    )
    itemrefs = "\n    ".join(f'<itemref idref="{s}"/>' for s in spine)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
{doctype}<package xmlns="http://www.idpf.org/2007/opf" version="{version}" unique-identifier="uid">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="uid">urn:bookscope:fixture:{title.lower().replace(" ", "-")}</dc:identifier>
    <dc:title>{title}</dc:title>
    <dc:language>en</dc:language>
    <meta property="dcterms:modified">2026-01-01T00:00:00Z</meta>
  </metadata>
  <manifest>
    {manifest}
  </manifest>
  <spine{toc_attr}>
    {itemrefs}
  </spine>
</package>
"""


def _nav(entries: list[tuple[str, str]]) -> str:
    lis = "\n".join(f'      <li><a href="{h}">{t}</a></li>' for h, t in entries)
    return _xhtml(
        "Contents",
        f'<nav epub:type="toc" id="toc"><h1>Contents</h1>\n    <ol>\n{lis}\n    </ol>\n  </nav>',
    )


